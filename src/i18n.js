// kamus di bawah memetakan teks Inggris → Bahasa Indonesia.
// Ganti bahasa me-reload halaman, jadi t() aman dipakai di konstanta tingkat modul.
import { getSettings, updateSettings } from './store.js';

export const LANGS = { en: 'English', id: 'Bahasa Indonesia' };

const current = LANGS[getSettings().lang] ? getSettings().lang : 'en';

export const lang = () => current;
export const locale = () => (current === 'id' ? 'id-ID' : 'en-US');

export function setLang(next) {
  if (!LANGS[next] || next === current) return;
  updateSettings({ lang: next });
  location.reload();
}

/** t('Remaining {time} for today', { time: '2h' }) */
export function t(text, vars) {
  let out = current === 'id' ? ID[text] ?? text : text;
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return out;
}

